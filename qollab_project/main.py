"""CHSH reference run (Python entry for Qollab).

Press Run: one job on the selected backend (a canary for bit order and readout
error, plus the four CHSH settings), then a claim card, then the precomputed
noise curve. Simulators compute what quantum theory predicts; they do not test nature.

This effort is supported by Qollab & IonQ
"""

import chsh
import qk_cards
import qk_data
import qk_runtime

DATASET = "data/chsh_noise.json"      # literal path: Qollab loads only files named literally
ATTRIBUTION = "This effort is supported by Qollab & IonQ"


def _noise_curve_text(ds, width=40):
    rows = [r for r in ds["results"]["rows"] if "S" in r]
    lines = ["Exact CHSH S vs two-qubit depolarizing strength p2 (precomputed):"]
    step = max(1, len(rows) // 12)
    for r in rows[::step]:
        s = r["S"]
        bar = "#" * max(0, int(round(width * s / chsh.SQRT8)))
        mark = "above 2" if s > 2 else "at/below 2"
        lines.append("  p2=%.3f  S=%.3f  %-*s %s" % (r["params"].get("p2", 0.0), s, width, bar, mark))
    d = ds["results"].get("derived", {})
    if "lambda_star_numeric" in d:
        lines.append("  S reaches 2 at p2 = %.4f (theory 1 - 1/sqrt(2) = %.4f)"
                     % (d["lambda_star_numeric"], d["lambda_star_theory"]))
    lines.append("  generated by %s at commit %s on a %s"
                 % (ds["generator"], ds["git_commit"], ds["machine"]))
    return "\n".join(lines)


