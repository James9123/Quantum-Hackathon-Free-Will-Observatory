"""Build qollab_project/ui/eggs.js: the Self's easter-egg animations (a bucket of water wakes it).

    .venv/bin/python tools/build_eggs.py <splash-1.gif> <splash-2.gif>

Each GIF is the team's 8-frame, 256 px, hard-alpha animation of the Self. Its frames are
area-averaged to the 128 px cells the portraits use, and again to 64 px for phones, with the
same rules as tools/build_sprites.py (hard alpha, the art's own palette); the strips are
embedded as data URIs because JavaScript on Qollab cannot fetch project files. No paths are
written to the output.
"""
import json
import os
import sys

from PIL import Image, ImageSequence

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_sprites import _data_uri, half  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "qollab_project", "ui", "eggs.js")
SRC = 256


def strip(path):
    gif = Image.open(path)
    frames = [f.convert("RGBA").copy() for f in ImageSequence.Iterator(gif)]
    durs = {f.info.get("duration") for f in ImageSequence.Iterator(Image.open(path))}
    if len(frames) != 8 or any(f.size != (SRC, SRC) for f in frames):
        raise SystemExit("%s: expected 8 frames of %d px" % (os.path.basename(path), SRC))
    for f in frames:
        if not set(f.getchannel("A").getdata()) <= {0, 255}:
            raise SystemExit("%s: alpha is not hard-edged" % os.path.basename(path))
    big = Image.new("RGBA", (SRC * 8, SRC), (0, 0, 0, 0))
    for i, f in enumerate(frames):
        big.paste(f, (i * SRC, 0))
    s128 = half(big)
    s64 = half(s128)
    ms = durs.pop() if len(durs) == 1 else 200
    return {"frames": 8, "fps": round(1000.0 / (ms or 200), 3),
            "src": {"128": _data_uri(s128), "64": _data_uri(s64)}}


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    data = {"self": [strip(p) for p in sys.argv[1:]]}
    text = "\n".join([
        "// The Self's easter-egg animations (a bucket of water wakes it). GENERATED by",
        "// tools/build_eggs.py from the team's GIFs; do not edit by hand. Each is one strip of 8",
        "// square cells, 128 px and a 64 px strip for phones; frame 1 is the frozen pose.",
        "",
        "export const EGGS = " + json.dumps(data, indent=1, sort_keys=True) + ";",
        "",
    ])
    with open(OUT, "w", encoding="ascii") as fh:
        fh.write(text)
    print("wrote %s (%d bytes)" % (os.path.relpath(OUT, ROOT), len(text)))


if __name__ == "__main__":
    main()
